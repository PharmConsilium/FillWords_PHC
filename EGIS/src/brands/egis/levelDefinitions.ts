export const assertEgisLevelDefinitions = (): void => {
  for (const [index, level] of EGIS_LEVEL_DEFINITIONS.entries()) {
    const expected = level.size * level.size;
    const actual = level.words.reduce((sum, word) => sum + wordLetterCount(word), 0);
    if (actual !== expected) {
      throw new Error(
        `Egis уровень ${index + 1}: сумма букв ${actual} != ${level.size}×${level.size} = ${expected}`,
      );
    }
  }
};

